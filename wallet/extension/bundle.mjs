// The extension's three content scripts (design §10.1). Content scripts are classic scripts: no `import`.
// The sources stay ES modules (unit-tested with `node --test`, shared with the hub and the fallback client) and
// are concatenated here with the same bundler as wallet/client.js (build-client.mjs bundleScript). Called by
// build-extension.mjs, which writes them to dist/extension/wallet/. Not committed: they are build output.
import { bundleScript } from '../build-client.mjs';

const HEADER = (name) => `/*! TapeKit extension: wallet/${name} (wallet routing, design §10.1). MIT licence.
 * Generated by build-extension.mjs from wallet/src and wallet/extension. Do not edit. */`;

export const CONTENT_SCRIPTS = Object.freeze({
  'inpage.js': {
    sources: ['src/protocol.js', 'src/provider.js', 'src/ext-protocol.js', 'extension/inpage.js'],
    start: ['installInpage(window);'],
  },
  'relay.js': {
    sources: ['src/protocol.js', 'src/ext-protocol.js', 'extension/relay.js'],
    start: ['startRelay({ win: window, runtime: chrome.runtime });'],
  },
  'hub-relay.js': {
    sources: ['src/protocol.js', 'src/ext-protocol.js', 'extension/hub-relay.js'],
    start: ['startHubRelay({ win: window, runtime: chrome.runtime });'],
  },
});

/** { 'inpage.js': code, 'relay.js': code, 'hub-relay.js': code } */
export function bundleContentScripts() {
  return Object.fromEntries(Object.entries(CONTENT_SCRIPTS).map(([name, { sources, start }]) => [
    name, bundleScript({ sources, header: HEADER(name), start, filename: name }),
  ]));
}
