// Builds wallet/client.js, the fallback client a site owner copies into the site's on-chain files (design §10.2).
//
// Why a generated, committed file: the site CSP only runs same-origin scripts and owners copy ONE file, so the
// client must be a single classic script with no imports. The sources stay ES modules (testable with
// `node --test`, shared with the hub); this script concatenates them inside one function scope:
//   wallet/src/protocol.js → wallet/src/provider.js → wallet/client/transport.js → wallet/client/install.js
// Their relative imports between each other are dropped and `export` is removed. Full-line comments and blank
// lines are dropped too: owners pay for every byte on chain. The chain table (kernel `siteNodes`, the same
// nodes the gateway lets sites reach) and the zh/en texts (wallet/src/i18n.js) are inlined as CONFIG.
// The output is committed so owners can copy it without Node; wallet/test/client.test.mjs fails when it is stale.
//
//   node wallet/build-client.mjs           write wallet/client.js
//   node wallet/build-client.mjs --check   exit 1 when wallet/client.js is not what the sources produce
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { NETWORKS } from '../kernel/src/config.js';
import { chainForArea, readNodes } from './src/chains.js';
import { tr } from './src/i18n.js';

const here = path.dirname(fileURLToPath(import.meta.url));
export const CLIENT_FILE = path.join(here, 'client.js');
const SOURCES = ['src/protocol.js', 'src/provider.js', 'client/transport.js', 'client/install.js'].map((f) => path.join(here, f));

const IMPORT_LINE = /^import\s*\{[^}]*\}\s*from\s*'(\.{1,2}\/[^']+)';\s*$/;
const DECLARATION = /^(?:export\s+)?(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/;

const HEADER = `/*! TapeKit wallet client (fallback channel). MIT licence. https://github.com/TapeOutProtocol/TapeKit
 * Copy this file into your site as tapekit-wallet.js and load it with <script src="tapekit-wallet.js"></script>.
 * It adds the "TapeKit" wallet (EIP-6963, window.tapekit.wallet); it never touches window.ethereum.
 * Generated by wallet/build-client.mjs from wallet/src/protocol.js, wallet/src/provider.js,
 * wallet/client/transport.js and wallet/client/install.js. Do not edit: run npm run build:wallet-client. */`;

/** Chain table and texts the client needs, from the same sources the hub and the gateway use. */
export function clientConfig() {
  const areaChains = Object.fromEntries(NETWORKS.map((net) => [net.area === null ? '' : String(net.area), chainForArea(net.area)]));
  const nodes = Object.fromEntries(Object.values(areaChains).map((hex) => [hex, [...readNodes(hex)]]));
  const both = (key) => ({ zh: tr('zh', key), en: tr('en', key) });
  return { areaChains, nodes, messages: { popup: both('err.popup'), closed: both('err.closed'), load: both('err.load') } };
}

/** One source file without its bundled imports, `export` keywords, full-line comments and blank lines. */
function strip(file, bundled) {
  const out = [];
  let inBlock = false;
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const t = line.trim();
    if (inBlock) { if (t.includes('*/')) inBlock = false; continue; }
    if (t.startsWith('/*')) { inBlock = !t.includes('*/'); continue; }
    if (!t || t.startsWith('//')) continue;
    // Lines are stripped one by one, so a template literal spanning lines could lose its blank or // lines.
    if ((line.match(/`/g) || []).length % 2) throw new Error(`${path.relative(here, file)}: multi-line template literals are not supported: ${t}`);
    const imp = IMPORT_LINE.exec(line);
    if (imp) {
      if (!bundled.has(path.resolve(path.dirname(file), imp[1]))) throw new Error(`${path.relative(here, file)}: import of a file that is not bundled: ${imp[1]}`);
      continue;
    }
    if (/^\s*(import|export)\b/.test(line) && !/^export\s+(async\s+)?(function|const|let|class)\b/.test(line)) {
      throw new Error(`${path.relative(here, file)}: unsupported module syntax: ${t}`);
    }
    out.push(line.replace(/^export\s+/, ''));
  }
  return out;
}

/** The client source text. Throws when a source uses module syntax the bundle cannot express. */
export function buildClient() {
  const bundled = new Set(SOURCES);
  const seen = new Map();
  const parts = SOURCES.map((file) => {
    const lines = strip(file, bundled);
    for (const line of lines) {
      const m = DECLARATION.exec(line);
      if (!m) continue;
      if (seen.has(m[1])) throw new Error(`top-level name ${m[1]} is declared in both ${seen.get(m[1])} and ${path.relative(here, file)}`);
      seen.set(m[1], path.relative(here, file));
    }
    return `// ---- ${path.relative(here, file)}\n${lines.join('\n')}`;
  });
  const code = [
    HEADER,
    '(() => {',
    "'use strict';",
    `const CONFIG = ${JSON.stringify(clientConfig(), null, 2)};`,
    ...parts,
    '// ---- start',
    'installClient(window, CONFIG);',
    '})();',
    '',
  ].join('\n');
  new vm.Script(code, { filename: 'client.js' });   // syntax check, including duplicate let/const/class
  return code;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const code = buildClient();
  const rel = path.relative(process.cwd(), CLIENT_FILE);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(CLIENT_FILE) ? fs.readFileSync(CLIENT_FILE, 'utf8') : '';
    if (current !== code) {
      console.error(`${rel} is stale: run npm run build:wallet-client`);
      process.exit(1);
    }
    console.log(`${rel} is up to date (${Buffer.byteLength(code)} bytes)`);
  } else {
    fs.writeFileSync(CLIENT_FILE, code);
    console.log(`wrote ${rel} (${Buffer.byteLength(code)} bytes)`);
  }
}
