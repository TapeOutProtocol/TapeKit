export type MsgKey = keyof Dict;
const LANG_KEY = 'tapesend:lang';
function chosenLang(): 'zh' | 'en' | null {
  try {
    const v = localStorage.getItem(LANG_KEY);
    return v === 'zh' || v === 'en' ? v : null;
  } catch {
    return null;
  }
}
const systemLang: 'zh' | 'en' = typeof navigator !== 'undefined' && !/^zh/i.test(navigator.language || '') ? 'en' : 'zh';
const lang: 'zh' | 'en' = chosenLang() ?? systemLang;
const dict: Dict = lang === 'en' ? en : zh;
export const t = (k: MsgKey) => dict[k];
export const locale = lang;
/** 切换语言：记在本机，重新加载界面（所有文字一次换好，不会中英混杂） */
export function setLocale(l: 'zh' | 'en') {
  if (l === lang) return;
  try { localStorage.setItem(LANG_KEY, l); } catch { /* 存不了就只对这次生效不了，保持原样 */ }
  window.location.reload();
}
